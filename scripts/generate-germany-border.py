"""Regenerates apps/mobile/src/map/germanyBorder.ts from Natural Earth v5.1.1.

Source (Public Domain): https://naciscdn.org/naturalearth/10m/cultural/ne_10m_admin_0_countries.zip
Usage: python3 -I scripts/generate-germany-border.py <ne_10m_admin_0_countries.shp> <output.ts>
Requires the GDAL Python bindings (osgeo). Not part of the app build.
"""
import sys

from osgeo import ogr, osr

BUFFER_M = 2500
SIMPLIFY_DEG = 0.004

ogr.UseExceptions()
osr.UseExceptions()


def srs(code):
    ref = osr.SpatialReference()
    ref.ImportFromEPSG(code)
    ref.SetAxisMappingStrategy(osr.OAMS_TRADITIONAL_GIS_ORDER)
    return ref


def main(shp_path, out_path):
    ds = ogr.Open(shp_path)
    layer = ds.GetLayer(0)
    layer.SetAttributeFilter("ADM0_A3 = 'DEU'")
    geom = None
    for feature in layer:
        part = feature.GetGeometryRef().Clone()
        geom = part if geom is None else geom.Union(part)
    if geom is None:
        raise SystemExit("No ADM0_A3 = 'DEU' feature found")

    wgs, utm = srs(4326), srs(25832)
    geom.Transform(osr.CoordinateTransformation(wgs, utm))
    geom = geom.Buffer(BUFFER_M, 8)
    geom.Transform(osr.CoordinateTransformation(utm, wgs))
    geom = geom.SimplifyPreserveTopology(SIMPLIFY_DEG)

    polys = (
        [geom.GetGeometryRef(i) for i in range(geom.GetGeometryCount())]
        if geom.GetGeometryType() == ogr.wkbMultiPolygon
        else [geom]
    )
    rings = []
    for poly in polys:
        pts = [(round(x, 3), round(y, 3)) for x, y, *_ in poly.GetGeometryRef(0).GetPoints()]
        ring = [pts[0]]
        for p in pts[1:]:
            if p != ring[-1]:
                ring.append(p)
        area2 = sum(a[0] * b[1] - b[0] * a[1] for a, b in zip(ring, ring[1:]))
        rings.append(ring if area2 > 0 else ring[::-1])  # counter-clockwise exteriors
    rings.sort(key=len, reverse=True)

    body = ",\n".join(
        "  [" + ",".join(f"[{x:g},{y:g}]" for x, y in ring) + "]" for ring in rings
    )
    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write(
            "// SPDX-License-Identifier: MPL-2.0\n"
            "// Copyright (C) 2026 OpenUnseal Contributors\n"
            "//\n"
            "// Generated by scripts/generate-germany-border.py. Border data: Natural Earth v5.1.1\n"
            "// ne_10m_admin_0_countries (Public Domain), buffered by 2.5 km and simplified.\n\n"
            "import type { Feature, MultiLineString, Polygon } from 'geojson';\n\n"
            "/** Counter-clockwise exterior rings of the buffered Germany outline. */\n"
            "export const GERMANY_BORDER_RINGS: readonly (readonly (readonly [number, number])[])[] = [\n"
            f"{body},\n];\n\n"
            "const WORLD_RING: [number, number][] = [\n"
            "  [-180, -85],\n  [180, -85],\n  [180, 85],\n  [-180, 85],\n  [-180, -85],\n];\n\n"
            "function copyRing(\n"
            "  ring: readonly (readonly [number, number])[],\n"
            "): [number, number][] {\n"
            "  return ring.map(([lng, lat]): [number, number] => [lng, lat]);\n}\n\n"
            "/** World polygon with Germany cut out (RFC 7946: clockwise holes). */\n"
            "export function buildGermanyInvertedMaskGeoJson(): Feature<Polygon> {\n"
            "  return {\n    type: 'Feature',\n    properties: {},\n    geometry: {\n"
            "      type: 'Polygon',\n      coordinates: [\n        WORLD_RING.map(([x, y]): [number, number] => [x, y]),\n"
            "        ...GERMANY_BORDER_RINGS.map((ring) => copyRing(ring).reverse()),\n      ],\n    },\n  };\n}\n\n"
            "export function buildGermanyBorderOutlineGeoJson(): Feature<MultiLineString> {\n"
            "  return {\n    type: 'Feature',\n    properties: {},\n    geometry: {\n"
            "      type: 'MultiLineString',\n      coordinates: GERMANY_BORDER_RINGS.map(copyRing),\n    },\n  };\n}\n"
        )
    print(f"{len(rings)} rings, {sum(map(len, rings))} points")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
